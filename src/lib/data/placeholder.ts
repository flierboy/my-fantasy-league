/** Snake draft order derived from each owner's draft_slot. */
export function getDraftOrder(owners: Owner[] = OWNERS): Owner[] {
  return [...owners]
    .filter((o) => o.draft_slot != null)
    .sort((a, b) => (a.draft_slot ?? 99) - (b.draft_slot ?? 99));
}
